package com.ioprogramming.csvdatahandling.advancedproblems.convertjsontocsv;

class Student {
    public int id;
    public String name;
    public int age;
    public double marks;

    // Constructors, Getters, and Setters
    public Student() {}
    public Student(int id, String name, int age, double marks) {
        this.id = id;
        this.name = name;
        this.age = age;
        this.marks = marks;
    }
}
